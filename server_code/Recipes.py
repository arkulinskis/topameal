BY_KEY = {t["key"]: t for t in TOPPERS}


def keeps(t):
    """Days the topper's shopping keeps after buying: its most perishable ingredient."""
    return min(GROCERIES[k][3] for k, _ in t["ing"])


def is_allowed(t, avoid, max_tier):
    avoid = set(avoid or [])
    if t["tier"] > max_tier:
        return False
    if "vegetarian" in avoid and "veg" not in t["tags"]:
        return False
    return not (avoid & set(t["tags"]))


def name_of(key):
    t = BY_KEY.get(key)
    return t["name"] if t else key
